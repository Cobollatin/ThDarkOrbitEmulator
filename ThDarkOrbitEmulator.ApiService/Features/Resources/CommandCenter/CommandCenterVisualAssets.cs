using System.Buffers.Binary;
using System.Collections.Concurrent;
using System.IO.Compression;
using System.Security.Cryptography;
using System.Text;
using System.Xml.Linq;

namespace ThDarkOrbitEmulator.ApiService.Features.Resources.CommandCenter;

// The manifest is captured, but the image bytes are not. These are local artwork
// for the visible news cards, indexed by the captured asset paths.
public static class CommandCenterVisualAssets
{
    // One manifest file entry. Hash is the captured 32-character version hash.
    public sealed record ManifestAsset(string Path, string Id, string Type, string Hash, string Version);

    // No manifest path is longer than this; longer request paths are never looked up.
    public const int MaxPathLength = 256;

    private static readonly Lazy<IReadOnlyDictionary<string, ManifestAsset>> Paths = new(() =>
    {
        var xml = XDocument.Parse(CapturedCommandCenterResources.Xml);
        var locations = xml.Root!.Elements("location").ToDictionary(
            e => (string)e.Attribute("id")!, e => (string)e.Attribute("path")!, StringComparer.Ordinal);
        return xml.Root.Elements("file")
            .Select(e => new ManifestAsset(
                "/" + locations[(string)e.Attribute("location")!] + (string)e.Attribute("name")! + "." + (string)e.Attribute("type")!,
                (string)e.Attribute("id")!,
                (string)e.Attribute("type")!,
                (string?)e.Attribute("hash") ?? string.Empty,
                (string?)e.Attribute("version") ?? "1"))
            .ToDictionary(a => a.Path, StringComparer.OrdinalIgnoreCase);
    });

    // Keyed and seeded by the canonical manifest path, so casing variants get identical bytes.
    private static readonly ConcurrentDictionary<string, byte[]> Artwork = new(StringComparer.Ordinal);

    public static bool IsManifestPath(string path) => Find(path) is not null;

    public static ManifestAsset? Find(string? path) =>
        !string.IsNullOrEmpty(path) && path.Length <= MaxPathLength && Paths.Value.TryGetValue(path, out var asset)
            ? asset : null;

    public static string? GetImagePath(string filename)
    {
        var path = "/do_img/new/bg/" + filename;
        return Find(path)?.Path;
    }

    public static byte[]? GetArtwork(string path) => Find(path) is { Type: "jpg" or "png" } asset
        ? Artwork.GetOrAdd(asset.Path, GeneratePng) : null;

    // Strong validator built from the manifest version hash; it changes when the manifest re-versions the file.
    public static string ETag(ManifestAsset asset) => "\"" + asset.Hash + "-" + asset.Version + "\"";

    public static bool IsNotModified(HttpRequest request, string etag)
    {
        foreach (var header in request.Headers.IfNoneMatch)
        {
            if (string.IsNullOrEmpty(header)) continue;
            foreach (var part in header.Split(','))
            {
                var tag = part.Trim();
                if (tag == "*" || tag == etag || tag == "W/" + etag) return true;
            }
        }
        return false;
    }

    // Serves generated artwork for a manifest JPG/PNG path, with 304 revalidation.
    // Returns false when the path is not such an entry so the caller can fall back.
    public static async Task<bool> TryWriteArtworkAsync(HttpContext context, CancellationToken ct)
    {
        var asset = Find(context.Request.Path.Value);
        var bytes = asset is null ? null : GetArtwork(asset.Path);
        if (asset is null || bytes is null) return false;
        var response = context.Response;
        var etag = ETag(asset);
        response.Headers.CacheControl = "public, max-age=3600";
        response.Headers.ETag = etag;
        response.Headers.XContentTypeOptions = "nosniff";
        if (IsNotModified(context.Request, etag))
        {
            response.StatusCode = StatusCodes.Status304NotModified;
            return true;
        }
        response.StatusCode = StatusCodes.Status200OK;
        response.ContentType = "image/png";
        response.ContentLength = bytes.Length;
        await response.Body.WriteAsync(bytes, ct);
        return true;
    }

    // Small deterministic space scene, 303x168, with a distinct palette per asset.
    // PNG is used even when the original manifest names a JPEG; the endpoint
    // advertises image/png to match the generated bytes.
    private static byte[] GeneratePng(string name)
    {
        const int width = 303, height = 168;
        var seed = SHA256.HashData(Encoding.UTF8.GetBytes(name));
        var pixels = new byte[height * (1 + width * 3)];
        var planetX = 75 + seed[0] % 155;
        var planetY = 42 + seed[1] % 82;
        var radius = 25 + seed[2] % 28;
        for (var y = 0; y < height; y++)
        {
            var row = y * (1 + width * 3);
            for (var x = 0; x < width; x++)
            {
                var i = row + 1 + x * 3;
                var d = (x - planetX) * (x - planetX) + (y - planetY) * (y - planetY);
                var star = ((x * 89 + y * 41 + seed[3]) % 997) < 2;
                var glow = d < radius * radius;
                var shade = (byte)Math.Clamp(20 + y / 7 + (x + seed[4]) % 12, 0, 255);
                pixels[i] = glow ? (byte)(75 + seed[5] % 130) : star ? (byte)225 : (byte)(shade / 2);
                pixels[i + 1] = glow ? (byte)(65 + seed[6] % 125) : star ? (byte)235 : shade;
                pixels[i + 2] = glow ? (byte)(110 + seed[7] % 125) : star ? (byte)255 : (byte)(shade + 30);
            }
        }

        using var output = new MemoryStream();
        output.Write(new byte[] { 137, 80, 78, 71, 13, 10, 26, 10 });
        var header = new byte[13];
        BinaryPrimitives.WriteInt32BigEndian(header, width);
        BinaryPrimitives.WriteInt32BigEndian(header.AsSpan(4), height);
        header[8] = 8; header[9] = 2;
        WriteChunk(output, "IHDR", header);
        using var compressed = new MemoryStream();
        using (var zlib = new ZLibStream(compressed, CompressionLevel.Fastest, leaveOpen: true))
            zlib.Write(pixels);
        WriteChunk(output, "IDAT", compressed.ToArray());
        WriteChunk(output, "IEND", []);
        return output.ToArray();
    }

    private static void WriteChunk(Stream output, string type, byte[] data)
    {
        Span<byte> number = stackalloc byte[4];
        BinaryPrimitives.WriteInt32BigEndian(number, data.Length);
        output.Write(number);
        var kind = Encoding.ASCII.GetBytes(type);
        output.Write(kind);
        output.Write(data);
        var crc = new Crc32();
        crc.Append(kind); crc.Append(data);
        BinaryPrimitives.WriteUInt32BigEndian(number, crc.Final);
        output.Write(number);
    }

    private sealed class Crc32
    {
        public uint Value { get; private set; } = 0xffffffff;
        public void Append(ReadOnlySpan<byte> bytes)
        {
            foreach (var value in bytes)
            {
                Value ^= value;
                for (var bit = 0; bit < 8; bit++)
                    Value = (Value >> 1) ^ ((Value & 1) != 0 ? 0xedb88320u : 0u);
            }
        }
        public uint Final => ~Value;
    }
}
